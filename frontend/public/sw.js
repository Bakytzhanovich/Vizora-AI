// Minimal service worker: only handles Web Push display + notification clicks.
// No offline caching — intentionally out of scope for this feature.

self.addEventListener("push", (event) => {
  if (!event.data) return;

  let payload = {};
  try {
    payload = event.data.json();
  } catch {
    payload = { title: "Vizora AI", body: event.data.text() };
  }

  const title = payload.title || "Vizora AI";
  const options = {
    body: payload.body || "",
    icon: "/brand/vizora-mark.png",
    badge: "/brand/vizora-mark.png",
    data: { url: payload.url || "/" },
  };

  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const targetUrl = event.notification.data?.url || "/";

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clients) => {
      for (const client of clients) {
        if (client.url.includes(targetUrl) && "focus" in client) {
          return client.focus();
        }
      }
      if (self.clients.openWindow) {
        return self.clients.openWindow(targetUrl);
      }
    })
  );
});
